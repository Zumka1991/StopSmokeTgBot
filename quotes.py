def get_achievement_for_time(minutes: int) -> str | None:
    """Получить достижение для определённого времени"""
    thresholds = {
        60: "1_hour",
        720: "12_hours",
        1440: "1_day",
        2880: "2_days",
        4320: "3_days",
        10080: "1_week",
        20160: "2_weeks",
        43200: "1_month",
        129600: "3_months",
        259200: "6_months",
        525600: "1_year",
        1051200: "2_years",
        2628000: "5_years",
        5256000: "10_years",
    }

    for threshold, achievement_key in thresholds.items():
        if minutes >= threshold and minutes < threshold + 1:
            return ACHIEVEMENT_MESSAGES.get(achievement_key)

    return None


def get_next_milestone(minutes: int) -> dict | None:
    """Получить следующую веху здоровья"""
    for milestone in HEALTH_MILESTONES:
        if milestone["minutes"] > minutes:
            return milestone
    return None
